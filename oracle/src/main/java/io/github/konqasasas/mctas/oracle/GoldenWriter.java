package io.github.konqasasas.mctas.oracle;

import io.github.konqasasas.mctas.physics.PlayerState;
import io.github.konqasasas.mctas.physics.testing.RandomScenario;
import io.github.konqasasas.mctas.physics.testing.StateHash;

import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;

/**
 * Writes the vanilla trajectory hash of each {@link RandomScenario}, so the physics module can
 * check itself against the game without the game on its classpath.
 *
 * <p>Usage: {@code GoldenWriter <out file> [runs] [ticks]}.
 */
public final class GoldenWriter {

    private GoldenWriter() {
    }

    public static void main(String[] args) throws IOException {
        String out = args[0];
        int runs = args.length > 1 ? Integer.parseInt(args[1]) : 1000;
        int ticks = args.length > 2 ? Integer.parseInt(args[2]) : 200;
        PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(out), StandardCharsets.UTF_8));
        try {
            w.println("# Generated by io.github.konqasasas.mctas.oracle.GoldenWriter from the 1.12.2 server jar.");
            w.println("# seed ticks hash-of-every-tick-state(hex)");
            for (long seed = 1; seed <= runs; seed++) {
                RandomScenario sc = RandomScenario.generate(seed, ticks);
                StateHash h = new StateHash();
                for (PlayerState s : new VanillaOracle(sc.world).run(sc.start, sc.inputs)) {
                    h.add(s);
                }
                w.println(seed + " " + ticks + " " + Long.toHexString(h.value()));
            }
        } finally {
            w.close();
        }
    }
}
